#!/usr/bin/env bash
# Manage the per-person bot containers of the web interface (fork-only).
#
#   ./webui/bots.sh add <name>      new bot container fgc-<name>, then docker compose up -d --build
#   ./webui/bots.sh remove <name>   remove the container (its data volume is kept)
#   ./webui/bots.sh list            show the bots
#   ./webui/bots.sh generate        only rewrite docker-compose.override.yml
#
# Options: --no-up  (do not run docker compose afterwards)
#
# Every bot is the upstream "app" service (via extends) with its own data volume,
# its own VNC password and no published ports. Only the web interface is published;
# it proxies each person's noVNC screen after login. The web container gets no
# Docker access at all: creating containers stays on the command line, here.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BOTS_DIR="$ROOT/webui/bots"
LIST="$BOTS_DIR/bots.list"
OVERRIDE="$ROOT/docker-compose.override.yml"
NAME_RE='^[a-z][a-z0-9_-]{0,31}$'

die() { echo "Fout: $*" >&2; exit 1; }
names() { [ -f "$LIST" ] && grep -E "$NAME_RE" "$LIST" || true; }

env_setting() {
	# A value from the project's .env (for WEBUI_PUBLIC_URL), without sourcing the file.
	[ -f "$ROOT/.env" ] || return 0
	sed -n "s/^[[:space:]]*$1[[:space:]]*=[[:space:]]*//p" "$ROOT/.env" | tail -n1 | sed "s/^['\"]//; s/['\"][[:space:]]*\$//"
}

generate() {
	local list csv name
	list="$(names)"
	{
		echo "# GENERATED by webui/bots.sh from webui/bots/bots.list. Do not edit: run ./webui/bots.sh generate."
		echo "# docker compose reads this file automatically next to docker-compose.yml (fork-only)."
		echo "# Needs Docker Compose 2.24 or newer (!reset / !override)."
		echo "services:"
		echo "  # The upstream single bot is replaced by one bot per person below."
		echo "  app:"
		echo "    profiles: [\"single\"]"
		for name in $list; do
			cat <<EOF

  fgc-$name:
    extends:
      file: docker-compose.yml
      service: app
    container_name: fgc-$name
    hostname: fgc-$name
    # No published ports: the web interface proxies this bot's noVNC after login.
    ports: !reset []
    volumes: !override
      - fgc_data_$name:/fgc/data
      - fgc_runlock:/fgc/runlock
    env_file: !override
      - webui/bots/$name.env
    environment:
      FGC_BOT_NAME: "$name"
      FGC_RUN_LOCK_DIR: /fgc/runlock
      FGC_RUN_TIMEOUT_MINUTES: "\${FGC_RUN_TIMEOUT_MINUTES:-180}"
EOF
		done
		csv="$(echo $list | tr ' ' ',')"
		cat <<EOF

  webui:
    build: ./webui
    image: fgc-webui:local
    container_name: fgc-webui
    restart: unless-stopped
    ports:
      - "\${WEBUI_BIND:-0.0.0.0}:\${WEBUI_PORT:-8090}:8000"
    env_file:
      - .env
    environment:
      FGC_BOTS: "$csv"
      WEBUI_DATA_DIR: /webui-data
    volumes:
      - webui_data:/webui-data
      - fgc_runlock:/runlock
      - ./webui/bots:/bots-env:ro
EOF
		for name in $list; do
			echo "      - fgc_data_$name:/bots/$name"
		done
		cat <<EOF
    read_only: true
    tmpfs:
      - /tmp
    cap_drop: [ALL]
    # Only to write config files owned by the bot's user and to read the bot env files.
    cap_add: [CHOWN, DAC_OVERRIDE, FOWNER]
    security_opt:
      - no-new-privileges:true

volumes:
  webui_data:
  fgc_runlock:
EOF
		for name in $list; do
			echo "  fgc_data_$name:"
		done
	} >"$OVERRIDE.tmp"
	mv "$OVERRIDE.tmp" "$OVERRIDE"
	echo "docker-compose.override.yml geschreven voor: ${list:-geen bots}" | tr '\n' ' '
	echo
}

compose_up() {
	[ "$NO_UP" = 1 ] && { echo "Start of werk bij met: docker compose up -d --build --remove-orphans"; return; }
	# Webui first: it writes each new bot's staggered schedule into the bot's volume at startup.
	# Starting the bots in the same step let a new bot read its config before that file existed,
	# so it ran on upstream defaults (every 12 h, run at startup).
	(cd "$ROOT" && docker compose up -d --build --remove-orphans --wait webui &&
		docker compose up -d --build --remove-orphans)
}

add() {
	local name="$1" url pw
	[[ "$name" =~ $NAME_RE ]] || die "een naam is 1-32 tekens: kleine letters, cijfers, - of _, beginnend met een letter."
	mkdir -p "$BOTS_DIR"
	chmod 700 "$BOTS_DIR"
	names | grep -qx "$name" && die "bot '$name' bestaat al."
	# TurboVNC uses at most 8 characters of a password.
	pw="$(set +o pipefail; LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 8)"
	url="$(env_setting WEBUI_PUBLIC_URL)"
	(
		umask 077
		{
			echo "# Docker settings of bot '$name' (generated by webui/bots.sh). Store accounts and"
			echo "# schedule are NOT set here but in the web interface (data/config.env in the bot's volume)."
			echo "VNC_PASSWORD=$pw"
			[ -n "$url" ] && echo "VNC_URL=${url%/}/vnc"
		} >"$BOTS_DIR/$name.env"
	)
	echo "$name" >>"$LIST"
	generate
	echo "Bot '$name' toegevoegd. Koppel hem in de webinterface (Beheer) aan een gebruiker."
	compose_up
}

remove() {
	local name="$1"
	names | grep -qx "$name" || die "bot '$name' bestaat niet."
	grep -vx "$name" "$LIST" >"$LIST.tmp" || true
	mv "$LIST.tmp" "$LIST"
	rm -f "$BOTS_DIR/$name.env"
	generate
	compose_up
	echo "Bot '$name' verwijderd. Zijn gegevens staan nog in volume fgc_data_$name;"
	echo "weggooien kan met: docker volume rm \$(docker volume ls -q | grep 'fgc_data_$name\$')"
}

NO_UP=0
args=()
for a in "$@"; do
	case "$a" in --no-up) NO_UP=1 ;; *) args+=("$a") ;; esac
done
set -- "${args[@]:-}"

case "${1:-}" in
	add) [ -n "${2:-}" ] || die "gebruik: $0 add <naam>"; add "$2" ;;
	remove) [ -n "${2:-}" ] || die "gebruik: $0 remove <naam>"; remove "$2" ;;
	list) names ;;
	generate) generate ;;
	*) sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
